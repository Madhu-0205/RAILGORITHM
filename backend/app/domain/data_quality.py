"""Data Quality and Confidence Assessment for RAILGORITHM.

Implements strict quality categorization, eligibility gating, and calibrated
confidence disclosures.

Data Quality Taxonomy:
- VERIFIED_SOURCE_DATA: Direct, cryptographically signed or hardware-validated telemetry
- OBSERVED: Direct sensor observation without redundant cross-check
- CALCULATED: Derived deterministically from observed data
- PREDICTED: Output of forward projection or statistical model
- SIMULATION: Generated by the internal synthetic simulation testbed
- HEURISTIC: Based on operational domain rules of thumb
- UNKNOWN: Data provenance cannot be verified
- STALE: Data was valid but exceeds freshness TTL
- CONFLICTING: Multiple sources report mutually incompatible readings
- NO_DATA: Required telemetry is completely missing
"""
from __future__ import annotations

from typing import Any

DATA_QUALITY_STATES = {
    "VERIFIED_SOURCE_DATA",
    "OBSERVED",
    "CALCULATED",
    "PREDICTED",
    "SIMULATION",
    "HEURISTIC",
    "UNKNOWN",
    "STALE",
    "CONFLICTING",
    "NO_DATA",
}

# Configured Source TTLs (in seconds)
SOURCE_TTLS = {
    "SIGNALLING_INTERLOCKING": 15,
    "TRACK_CIRCUIT_OCCUPANCY": 10,
    "GPS_LOCOMOTIVE_FEED": 30,
    "CAUTION_ORDERS": 1800,
    "WORKING_TIMETABLE": 86400,
}


def evaluate_data_quality(state: dict, feed_health: Any = None) -> dict:
    """Evaluate data quality across all inputs required for train regulation.

    Implements explicit eligibility gating across HEALTHY, DEGRADED, STALE, OFFLINE,
    CONTRADICTORY, INCOMPLETE, and UNKNOWN states.
    """
    now = int(state.get("sim_time_min", 0))
    trains = state.get("trains", [])
    network = state.get("network", {})

    items: dict[str, dict] = {}
    issues: list[str] = []
    has_critical_error = False
    has_stale = False
    has_contradictory = False
    has_offline = False
    has_incomplete = False

    override = state.get("_telemetry_quality_override")
    if override == "OFFLINE":
        has_offline = True
        has_critical_error = True
        issues.append("Signalling feed is OFFLINE.")
    elif override == "STALE":
        has_stale = True
        has_critical_error = True
        issues.append("Signalling feed is STALE.")
    elif override == "CONTRADICTORY":
        has_contradictory = True
        has_critical_error = True
        issues.append("Contradictory train positions detected.")
    elif override == "INCOMPLETE":
        has_incomplete = True
        has_critical_error = True
        issues.append("Incomplete telemetry detected.")

    # 1. Signalling & Telemetry Feed Health
    if override:
        items["signal_feed"] = {
            "quality_state": override,
            "detail": f"Signalling telemetry feed status: {override}.",
            "freshness_seconds": 9999 if override == "STALE" else 0,
            "ttl_seconds": SOURCE_TTLS["SIGNALLING_INTERLOCKING"],
            "critical": True,
        }
    elif feed_health is not None:
        feed_status = getattr(feed_health, "status", "UNKNOWN")
        is_stale = getattr(feed_health, "is_stale", False)
        freshness_sec = getattr(feed_health, "freshness_seconds", 0)
        feed_id = getattr(feed_health, "feed_id", "FEED-SIGNAL-01")

        if feed_status in {"OFFLINE", "ERROR"}:
            items["signal_feed"] = {
                "quality_state": "OFFLINE",
                "detail": f"Signalling telemetry feed '{feed_id}' is OFFLINE.",
                "freshness_seconds": freshness_sec,
                "ttl_seconds": SOURCE_TTLS["SIGNALLING_INTERLOCKING"],
                "critical": True,
            }
            issues.append(f"Signalling feed '{feed_id}' is OFFLINE.")
            has_offline = True
            has_critical_error = True
        elif is_stale or feed_status == "STALE" or freshness_sec > SOURCE_TTLS["SIGNALLING_INTERLOCKING"]:
            items["signal_feed"] = {
                "quality_state": "STALE",
                "detail": f"Signalling feed '{feed_id}' telemetry is STALE ({freshness_sec}s > {SOURCE_TTLS['SIGNALLING_INTERLOCKING']}s threshold).",
                "freshness_seconds": freshness_sec,
                "ttl_seconds": SOURCE_TTLS["SIGNALLING_INTERLOCKING"],
                "critical": True,
            }
            issues.append(f"Signalling feed '{feed_id}' data is stale.")
            has_stale = True
        else:
            items["signal_feed"] = {
                "quality_state": "HEALTHY",
                "detail": f"Signalling feed '{feed_id}' is operational and fresh ({freshness_sec}s age).",
                "freshness_seconds": freshness_sec,
                "ttl_seconds": SOURCE_TTLS["SIGNALLING_INTERLOCKING"],
                "critical": True,
            }
    else:
        items["signal_feed"] = {
            "quality_state": "HEALTHY",
            "detail": "Synthetic simulation testbed feed (internal generation).",
            "freshness_seconds": 0,
            "ttl_seconds": SOURCE_TTLS["SIGNALLING_INTERLOCKING"],
            "critical": True,
        }

    # 2. Train Positions, Identifiers & Movement Checks
    train_count = len(trains)
    if train_count == 0:
        items["train_positions"] = {
            "quality_state": "NO_DATA",
            "detail": "No train telemetry is available in the operational state.",
            "critical": True,
        }
        issues.append("No train telemetry found in state.")
        has_incomplete = True
        has_critical_error = True
    else:
        corrupt_trains = []
        missing_identity = []
        for t in trains:
            tid = t.get("id")
            if not tid or not isinstance(tid, str) or len(tid) < 2:
                missing_identity.append(str(tid))
            status = t.get("status")
            if status == "RUNNING" and not t.get("block_id"):
                corrupt_trains.append(f"{tid} (running without assigned block)")
            elif status == "AT_STATION" and not t.get("station_id"):
                corrupt_trains.append(f"{tid} (at_station without station_id)")

        if missing_identity:
            items["train_identities"] = {
                "quality_state": "INCOMPLETE",
                "detail": f"Missing or invalid train identifiers: {', '.join(missing_identity)}",
                "critical": True,
            }
            issues.append(f"Missing train identities for {len(missing_identity)} train(s).")
            has_incomplete = True
            has_critical_error = True

        if corrupt_trains:
            items["train_positions"] = {
                "quality_state": "CONTRADICTORY",
                "detail": f"Contradictory location telemetry: {'; '.join(corrupt_trains)}",
                "critical": True,
            }
            issues.append(f"Contradictory train positions detected for {len(corrupt_trains)} train(s).")
            has_contradictory = True
            has_critical_error = True
        else:
            items["train_positions"] = {
                "quality_state": "HEALTHY",
                "detail": f"{train_count} active train position records validated against route continuity.",
                "critical": True,
            }

    # 3. Network Topology & Block Exclusivity Geometry
    stations = network.get("stations", [])
    sections = network.get("sections", [])
    total_blocks = sum(len(sec.get("blocks", [])) for sec in sections)
    if not stations or not sections or total_blocks == 0:
        items["topology"] = {
            "quality_state": "INCOMPLETE",
            "detail": "Network infrastructure geometry or block definition is missing.",
            "critical": True,
        }
        issues.append("Network infrastructure geometry missing.")
        has_incomplete = True
        has_critical_error = True
    else:
        items["topology"] = {
            "quality_state": "HEALTHY",
            "detail": f"Full topology validated: {len(stations)} stations, {len(sections)} sections, {total_blocks} blocks.",
            "critical": True,
        }

    # 4. Schedule & Working Timetable
    items["timetable"] = {
        "quality_state": "HEALTHY",
        "detail": "Working Timetable (WTT) and sectional running allowances loaded.",
        "critical": False,
    }

    # Determine Overall Quality Classification & Recommendation Eligibility Gate
    if has_offline:
        overall_state = "OFFLINE"
        eligibility = {
            "is_eligible": False,
            "eligibility_gate": "BLOCKED",
            "gate_reason": "Signalling telemetry is OFFLINE. System cannot guarantee current operational awareness.",
            "allowed_recommendation_scope": "NONE",
        }
    elif has_contradictory:
        overall_state = "CONTRADICTORY"
        eligibility = {
            "is_eligible": False,
            "eligibility_gate": "BLOCKED",
            "gate_reason": "Contradictory train position reports detected. Safety rules forbid automated advisory under spatial ambiguity.",
            "allowed_recommendation_scope": "NONE",
        }
    elif has_incomplete:
        overall_state = "INCOMPLETE"
        eligibility = {
            "is_eligible": False,
            "eligibility_gate": "BLOCKED",
            "gate_reason": "Required operational telemetry or topology geometry is INCOMPLETE.",
            "allowed_recommendation_scope": "NONE",
        }
    elif has_stale:
        overall_state = "STALE"
        eligibility = {
            "is_eligible": False,
            "eligibility_gate": "WITHHELD",
            "gate_reason": "Signalling telemetry is STALE (exceeds freshness TTL). Fresh telemetry required before issuing recommendations.",
            "allowed_recommendation_scope": "NONE",
        }
    elif any(it["quality_state"] == "DEGRADED" for it in items.values()):
        overall_state = "DEGRADED"
        eligibility = {
            "is_eligible": True,
            "eligibility_gate": "LIMITED",
            "gate_reason": "Telemetry degraded. Recommendations limited to low-risk regulation with expanded safety headways.",
            "allowed_recommendation_scope": "LIMITED_ADVISORY",
        }
    else:
        overall_state = "SIMULATION" if (state.get("label") == "SYNTHETIC" or not feed_health) else "HEALTHY"
        eligibility = {
            "is_eligible": True,
            "eligibility_gate": "PASSED",
            "gate_reason": "All operational inputs verified healthy, fresh, and consistent.",
            "allowed_recommendation_scope": "FULL",
        }

    return {
        "overall_quality_state": overall_state,
        "is_eligible_for_recommendations": eligibility["is_eligible"],
        "eligibility": eligibility,
        "stale_input_warning": has_stale,
        "items": items,
        "issues": issues,
        "assessment_timestamp": now,
    }


def get_confidence_disclosure(
    is_calibrated: bool = False,
    calibration_metrics: dict | None = None,
    uncertainty_range_min: float | None = None,
    disagreement: bool = False,
    data_quality_state: str = "HEALTHY",
) -> dict:
    """Return calibrated confidence disclosure following Indian Railways decision support safety rules.

    Explicitly refuses to fabricate numerical confidence percentages without a formal calibration pipeline.
    """
    has_issues = data_quality_state in {"DEGRADED", "STALE", "OFFLINE", "CONTRADICTORY", "INCOMPLETE"}

    if not is_calibrated:
        return {
            "confidence_label": "Confidence: Not calibrated",
            "is_calibrated": False,
            "display_percentage": None,
            "insufficient_evidence": has_issues,
            "data_quality_degraded": has_issues,
            "model_disagreement": disagreement,
            "prediction_uncertainty_range_min": uncertainty_range_min if uncertainty_range_min is not None else 4.0,
            "explanation": (
                "RAILGORITHM strictly refuses to invent uncalibrated confidence percentages. "
                "Recommendations are evaluated based on deterministic constraint verification, "
                "categorical evidence provenance, and cloned simulation outcomes."
            ),
            "safety_note": (
                "Advisory decision support only. The Section Controller remains the "
                "sole operating authority."
            ),
        }

    return {
        "confidence_label": "Confidence: Calibrated",
        "is_calibrated": True,
        "display_percentage": calibration_metrics.get("expected_calibration_error") if calibration_metrics else None,
        "calibration_method": (calibration_metrics or {}).get("method", "Temperature Scaling"),
        "brier_score": (calibration_metrics or {}).get("brier_score"),
        "validation_sample_size": (calibration_metrics or {}).get("sample_size"),
        "insufficient_evidence": has_issues,
        "data_quality_degraded": has_issues,
        "model_disagreement": disagreement,
        "prediction_uncertainty_range_min": uncertainty_range_min or 2.0,
    }
